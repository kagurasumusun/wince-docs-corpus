_FUNC_RES = [(re.compile(pat), hdr) for pat, hdr in FUNCTION_PREFIX_TO_HEADER]


def _prefix_ok(name: str, prefix: str) -> bool:
    rest = name[len(prefix):]
    min_rest = _SHORT_PREFIX_MIN_REST.get(prefix)
    if min_rest is not None and len(rest) < min_rest:
        return False
    # HTCLIENT is ok; HTMLFOX is not a hit-test code
    if prefix == "HT" and rest and not rest.isupper() and "_" not in name:
        return False
    if prefix == "E_" and not re.match(r"^[A-Z][A-Z0-9_]+$", rest):
        return False
    return True


def _sorted_prefixes():
    return sorted(PREFIX_TO_HEADER, key=len, reverse=True)


_PREFIXES_LONGEST = None


def prefixes_longest():
    global _PREFIXES_LONGEST
    if _PREFIXES_LONGEST is None:
        _PREFIXES_LONGEST = _sorted_prefixes()
    return _PREFIXES_LONGEST


def header_for_constant(name: str) -> str | None:
    """Return the conventional header for a constant / macro name, or None."""
    if not name:
        return None
    exact = EXACT_TO_HEADER.get(name)
    if exact:
        return exact
    for prefix in prefixes_longest():
        if name.startswith(prefix) and _prefix_ok(name, prefix):
            return PREFIX_TO_HEADER[prefix]
    return None


def header_for_entity(name: str, kinds=None) -> str | None:
    """Header for an API / type / constant entity name."""
    if not name:
        return None
    h = header_for_constant(name)
    if h:
        return h
    # Enum/struct named after a known prefix: CLSCTX -> CLSCTX_ -> Objbase.h
    prefixed = name + "_"
    if prefixed in PREFIX_TO_HEADER:
        return PREFIX_TO_HEADER[prefixed]
    kinds = kinds or []
    if any(k in ("macro", "enum") for k in kinds) or (
            name.isupper() and "_" in name):
        h = header_for_constant(name)
        if h:
            return h
    for cre, hdr in _FUNC_RES:
        if cre.match(name):
            return hdr
    if name.startswith("D3DM"):
        return "D3dm.h"
    if name.startswith("D3D"):
        return "D3dm.h"
    if name.startswith(("IDirectDraw", "IDirect3D")):
        return "Ddraw.h" if "Draw" in name else "D3dm.h"
    return None


def header_for_library(lib: str) -> str | None:
    """Header uniquely associated with a library/DLL stem, or None."""
    if not lib:
        return None
    stem = re.sub(r"\.(lib|dll|exe|drv|sys)$", "", lib.strip(), flags=re.I)
    stem = stem.split("\\")[-1].split("/")[-1].lower()
    return LIBRARY_TO_HEADER.get(stem)


def canonical_header(name: str) -> str:
    """Normalise a header file spelling (Winuser.h)."""
    if not name:
        return name
    base = name.split("/")[-1].split("\\")[-1].strip().rstrip(". ")
    if not base:
        return name
    # keep well-known casing when we know it
    lower = base.lower()
    for table in (PREFIX_TO_HEADER, EXACT_TO_HEADER, LIBRARY_TO_HEADER):
        for v in table.values():
            if v.lower() == lower:
                return v
    if "." in base:
        stem, ext = base.rsplit(".", 1)
        return stem[:1].upper() + stem[1:] + "." + ext.lower()
    return base
